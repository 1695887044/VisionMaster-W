# sync_constraints.ps1 - mirror the load-bearing constraints of AGENTS.md into
# the ZCode global rules file (~/.zcode/AGENTS.md).
#
# Single source of truth: <repo>\AGENTS.md  (read by DSH only).
# Mirror target:          %USERPROFILE%\.zcode\AGENTS.md (read by ZCode only).
#
# Design rules honoured here:
#   R1  this script is pure ASCII (no CJK literals in source).
#   R2  CJK content is loaded from a UTF-8 JSON sidecar, never inlined.
#   R4  the target is rewritten with UTF8Encoding($false) - no BOM.
#   R180 replace-style writes catch IOException AND UnauthorizedAccessException.
#
# Only the block between DSH-SYNC:BEGIN and DSH-SYNC:END is replaced.
# Everything outside it is preserved byte for byte. The run is idempotent.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File tools\sync_constraints.ps1
#   powershell -ExecutionPolicy Bypass -File tools\sync_constraints.ps1 -Check
#     -Check : report drift only, write nothing (exit 1 when drifted).

[CmdletBinding()]
param(
    [string]$RepoRoot = '',
    [string]$TargetPath = '',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'

# $PSScriptRoot is empty while default parameter values are bound under
# -File in some PowerShell builds, so resolve the paths here instead.
if ([string]::IsNullOrWhiteSpace($PSScriptRoot)) {
    $scriptFull = $MyInvocation.MyCommand.Path
    if ([string]::IsNullOrWhiteSpace($scriptFull)) {
        Write-Host 'FATAL: cannot resolve script location.' -ForegroundColor Red
        exit 2
    }
    $scriptDir = Split-Path -Parent $scriptFull
} else {
    $scriptDir = $PSScriptRoot
}
if ([string]::IsNullOrWhiteSpace($RepoRoot)) { $RepoRoot = Split-Path -Parent $scriptDir }
if ([string]::IsNullOrWhiteSpace($TargetPath)) {
    $TargetPath = Join-Path $env:USERPROFILE '.zcode\AGENTS.md'
}
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# Console must speak UTF-8 or every CJK path in the report turns into '?'.
try { [Console]::OutputEncoding = $utf8NoBom } catch { }

$beginMarker = '<!-- DSH-SYNC:BEGIN (generated by tools/sync_constraints.ps1 - do not edit by hand) -->'
$endMarker   = '<!-- DSH-SYNC:END -->'

function Read-Utf8 {
    param([string]$Path)
    if (-not (Test-Path -LiteralPath $Path)) { return $null }
    $bytes = [IO.File]::ReadAllBytes($Path)
    $enc = New-Object System.Text.UTF8Encoding($false, $true)
    return $enc.GetString($bytes)
}

function Write-Utf8Atomic {
    param([string]$Path, [string]$Text)
    $Path = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
    # Write through a fresh temp file, then swap. R180: File.Replace is
    # rejected in some restricted hosts, so a copy fallback is mandatory and
    # must catch IOException as well as UnauthorizedAccessException.
    $tmp = "$Path.dshsync.tmp"
    [IO.File]::WriteAllText($tmp, $Text, (New-Object System.Text.UTF8Encoding($false)))
    try {
        if (Test-Path -LiteralPath $Path) {
            [IO.File]::Replace($tmp, $Path, $null)
        } else {
            [IO.File]::Move($tmp, $Path)
        }
        return
    }
    catch [System.IO.IOException] { }
    catch [System.UnauthorizedAccessException] { }
    catch [System.ArgumentException] { }
    if (Test-Path -LiteralPath $tmp) {
        [IO.File]::Copy($tmp, $Path, $true)
        Remove-Item -LiteralPath $tmp -Force
    }
}

# ---------------------------------------------------------------------------
# Load the CJK block body from the UTF-8 sidecar.
# ---------------------------------------------------------------------------
$sidecar = Join-Path $scriptDir 'sync_constraints.block.json'
if (-not (Test-Path -LiteralPath $sidecar)) {
    Write-Host "FATAL: sidecar not found: $sidecar" -ForegroundColor Red
    exit 2
}
$json = Read-Utf8 -Path $sidecar
if ($null -eq $json) { Write-Host "FATAL: cannot read sidecar" -ForegroundColor Red; exit 2 }
$cfg = $json | ConvertFrom-Json

$agentsPath = Join-Path $RepoRoot 'AGENTS.md'
if (-not (Test-Path -LiteralPath $agentsPath)) {
    Write-Host "FATAL: AGENTS.md not found at $agentsPath" -ForegroundColor Red
    exit 2
}
$agentsInfo = Get-Item -LiteralPath $agentsPath
$agentsStamp = '{0} bytes, last write {1:yyyy-MM-dd HH:mm}' -f $agentsInfo.Length, $agentsInfo.LastWriteTime
if ($agentsInfo.Length -gt 56000) {
    Write-Host ("WARN: AGENTS.md is {0} bytes, above the 56000 soft ceiling." -f $agentsInfo.Length) -ForegroundColor Yellow
}

$bodyLines = New-Object System.Collections.Generic.List[string]
$bodyLines.Add($cfg.heading)
$bodyLines.Add('')
$bodyLines.Add(($cfg.note -f 'D:\C#\VM\AGENTS.md', $agentsStamp))
$bodyLines.Add('')
foreach ($rule in $cfg.rules) {
    $bodyLines.Add("### $($rule.title)")
    foreach ($line in $rule.lines) { $bodyLines.Add("- $line") }
    $bodyLines.Add('')
}
$bodyLines.Add($cfg.footer)
$blockBody = ($bodyLines -join "`r`n")

$newBlock = $beginMarker + "`r`n" + $blockBody + "`r`n" + $endMarker

# ---------------------------------------------------------------------------
# Splice into the existing target.
# ---------------------------------------------------------------------------
$old = Read-Utf8 -Path $TargetPath
if ($null -eq $old) {
    $old = $cfg.seedHeader + "`r`n"
    $hasBlock = $false
} else {
    $hasBlock = ($old.Contains($beginMarker) -and $old.Contains($endMarker))
}

if ($hasBlock) {
    $startIdx = $old.IndexOf($beginMarker)
    $endIdx = $old.IndexOf($endMarker, $startIdx)
    $afterEnd = $endIdx + $endMarker.Length
    $before = $old.Substring(0, $startIdx)
    $after = $old.Substring($afterEnd)
    $updated = $before + $newBlock + $after
} else {
    if ($old.Length -gt 0 -and -not $old.EndsWith("`n")) { $old += "`r`n" }
    $updated = $old + "`r`n" + $newBlock + "`r`n"
}

$drift = ($null -eq (Read-Utf8 -Path $TargetPath)) -or ($updated -ne $old)

if ($Check) {
    if (-not (Test-Path -LiteralPath $TargetPath)) {
        Write-Host "DRIFT: target does not exist: $TargetPath"
        exit 1
    }
    if ($updated -ne $old) {
        Write-Host "DRIFT: $TargetPath is out of sync with AGENTS.md ($agentsStamp)."
        Write-Host "       Run tools\sync_constraints.ps1 to refresh."
        exit 1
    }
    Write-Host "IN SYNC: $TargetPath"
    exit 0
}

if (-not $drift) {
    Write-Host "IN SYNC (no change written): $TargetPath"
    exit 0
}

Write-Utf8Atomic -Path $TargetPath -Text $updated

# Read back and prove the splice survived a real UTF-8 round trip (R5).
$verify = Read-Utf8 -Path $TargetPath
if ($null -eq $verify) { Write-Host "FAIL: cannot read back $TargetPath" -ForegroundColor Red; exit 3 }
if (-not $verify.Contains($beginMarker)) { Write-Host "FAIL: begin marker missing after write" -ForegroundColor Red; exit 3 }
if (-not $verify.Contains($endMarker))   { Write-Host "FAIL: end marker missing after write" -ForegroundColor Red; exit 3 }
$probe = $cfg.rules[0].title
if (-not $verify.Contains($probe)) { Write-Host "FAIL: CJK probe text did not survive the round trip" -ForegroundColor Red; exit 3 }

$bom = [IO.File]::ReadAllBytes($TargetPath)
if ($bom.Length -ge 3 -and $bom[0] -eq 0xEF -and $bom[1] -eq 0xBB -and $bom[2] -eq 0xBF) {
    Write-Host "FAIL: target now carries a UTF-8 BOM (R3/R4)" -ForegroundColor Red
    exit 3
}

Write-Host ""
Write-Host "SYNCED: $TargetPath"
Write-Host ("  source : {0} ({1})" -f $agentsPath, $agentsStamp)
Write-Host ("  rules  : {0}" -f $cfg.rules.Count)
Write-Host ("  size   : {0} bytes (was {1})" -f $verify.Length, $(if ($null -eq $old) { 0 } else { $old.Length }))
exit 0
