<#
.SYNOPSIS
  Move the retired ZCode desktop state into _Retired\ (2026-10-24).

.DESCRIPTION
  When the ZCode desktop client is retired its own working directories under
  .zcode\ become dead weight: DSH never reads them, they are not documentation,
  and they carry no authorship value once the plans are archived in docs\.

  What this script does, per item:
    .zcode\plans\*.md          -> _Retired\<stamp>-zcode-desktop-state\plans\
    .zcode\workflow-drafts\*   -> _Retired\<stamp>-zcode-desktop-state\workflow-drafts\

  What it deliberately keeps in place:
    .zcode\skills\**           referenced verbatim by AGENTS.md R106 and the
                               skill appendix; moving them would break those
                               pointers. Not touched.
    .zcode\workflow-runs\.gitignore, .zcode\workflow-drafts\.gitignore
                               generated by the tool, left alone so a revival
                               of the tool does not start dirty.

  .mjs run scripts are machine generated ("safe to delete once the run has
  settled", per their own header) and are NOT archived: they are pure noise.

  Dry run by default. Pass -Apply to actually move. Writes a README.md with the
  inventory inside the destination (R168: every _Retired folder carries one).

  Body text of the generated README comes from tools\retire_zcode_state.text.json
  (UTF-8) because this script must stay pure ASCII: PowerShell 5.1 reads a
  BOM-less UTF-8 .ps1 as code page 936 and mangles any Chinese literal.

.PARAMETER Root
  Repository root. Defaults to the parent directory of this script.

.PARAMETER Stamp
  Destination folder prefix. Defaults to today (yyyy-MM-dd).

.PARAMETER Apply
  Perform the moves. Without it the script only prints the plan.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\retire_zcode_state.ps1

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File tools\retire_zcode_state.ps1 -Apply
#>
[CmdletBinding()]
param(
    [string]$Root = '',
    [string]$Stamp = '',
    [switch]$Apply
)

$ErrorActionPreference = 'Stop'

try {
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [Console]::OutputEncoding = $utf8NoBom
    $OutputEncoding = $utf8NoBom
} catch {
    # Non-interactive host: keep whatever encoding is in effect.
}

function Write-Utf8File {
    param([string]$Path, [string[]]$Lines)
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
    $text = ($Lines -join "`r`n") + "`r`n"
    [IO.File]::WriteAllText($Path, $text, (New-Object System.Text.UTF8Encoding($false)))
}

if ([string]::IsNullOrWhiteSpace($Root)) {
    $Root = Split-Path -Parent $PSScriptRoot
}
$Root = [IO.Path]::GetFullPath($Root)
if ([string]::IsNullOrWhiteSpace($Stamp)) { $Stamp = Get-Date -Format 'yyyy-MM-dd' }

$zcode = Join-Path $Root '.zcode'
$destName = $Stamp + '-zcode-desktop-state'
$dest = Join-Path (Join-Path $Root '_Retired') $destName

$plan = @(
    @{ Src = (Join-Path $zcode 'plans');           Sub = 'plans';           Pattern = '*.md' },
    @{ Src = (Join-Path $zcode 'workflow-drafts'); Sub = 'workflow-drafts'; Pattern = '*' }
)

$moved = New-Object System.Collections.Generic.List[string]
$skipped = New-Object System.Collections.Generic.List[string]
$deleted = New-Object System.Collections.Generic.List[string]

$modeText = 'DRY-RUN (pass -Apply to move)'
if ($Apply) { $modeText = 'APPLY' }
Write-Host ('mode   : ' + $modeText)
Write-Host ('source : ' + $zcode)
Write-Host ('dest   : ' + $dest)
Write-Host ''

foreach ($item in $plan) {
    if (-not (Test-Path -LiteralPath $item.Src)) {
        $skipped.Add($item.Sub + ' : source missing')
        continue
    }
    $files = @(Get-ChildItem -LiteralPath $item.Src -File -Filter $item.Pattern |
               Where-Object { $_.Name -ne '.gitignore' })
    if ($files.Count -eq 0) {
        $skipped.Add($item.Sub + ' : nothing to move')
        continue
    }
    $targetDir = Join-Path $dest $item.Sub
    if ($Apply -and -not (Test-Path -LiteralPath $targetDir)) {
        New-Item -ItemType Directory -Force -Path $targetDir | Out-Null
    }
    foreach ($f in $files) {
        $target = Join-Path $targetDir $f.Name
        Write-Host ('  move  .zcode\' + $item.Sub + '\' + $f.Name)
        if ($Apply) {
            if (Test-Path -LiteralPath $target) { Remove-Item -LiteralPath $target -Force }
            Move-Item -LiteralPath $f.FullName -Destination $target
        }
        $moved.Add('.zcode/' + $item.Sub + '/' + $f.Name)
    }
}

# generated run scripts: noise, do not archive
$runDir = Join-Path $zcode 'workflow-runs'
if (Test-Path -LiteralPath $runDir) {
    foreach ($f in (Get-ChildItem -LiteralPath $runDir -File -Filter '*.mjs')) {
        Write-Host ('  del   .zcode\workflow-runs\' + $f.Name + '  (generated)')
        if ($Apply) { Remove-Item -LiteralPath $f.FullName -Force }
        $deleted.Add('.zcode/workflow-runs/' + $f.Name)
    }
}

if ($Apply) {
    $textPath = Join-Path $PSScriptRoot 'retire_zcode_state.text.json'
    if (-not (Test-Path -LiteralPath $textPath)) {
        Write-Host ('TEXT MISSING: ' + $textPath)
        exit 2
    }
    $txt = ([IO.File]::ReadAllText($textPath, [Text.Encoding]::UTF8)) | ConvertFrom-Json

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# ' + $destName)
    $lines.Add('')
    foreach ($p in $txt.intro) { $lines.Add($p) }
    $lines.Add('')
    $lines.Add('## ' + $txt.movedHeading)
    $lines.Add('')
    $lines.Add('| ' + $txt.colSource + ' | ' + $txt.colNote + ' |')
    $lines.Add('|---|---|')
    foreach ($m in $moved) {
        $code = $txt.noteOther
        if ($m -like '*.md') { $code = $txt.noteMd }
        elseif ($m -like '*.ts') { $code = $txt.noteTs }
        $lines.Add('| `' + $m + '` | ' + $code + ' |')
    }
    $lines.Add('')
    if ($deleted.Count -gt 0) {
        $lines.Add('## ' + $txt.deletedHeading)
        $lines.Add('')
        foreach ($p in $txt.deletedIntro) { $lines.Add($p) }
        $lines.Add('')
        foreach ($d in $deleted) { $lines.Add('- `' + $d + '`') }
        $lines.Add('')
    }
    $lines.Add('## ' + $txt.keptHeading)
    $lines.Add('')
    foreach ($k in $txt.kept) { $lines.Add('- ' + $k) }
    $lines.Add('')
    $lines.Add('## ' + $txt.restoreHeading)
    $lines.Add('')
    foreach ($p in $txt.restoreBody) { $lines.Add($p) }
    $lines.Add('')
    $lines.Add('## ' + $txt.deleteHeading)
    $lines.Add('')
    foreach ($p in $txt.deleteBody) { $lines.Add($p) }

    $readme = Join-Path $dest 'README.md'
    Write-Utf8File -Path $readme -Lines $lines.ToArray()
    Write-Host ''
    Write-Host ('README : ' + $readme)
}

Write-Host ''
Write-Host ('MOVED=' + $moved.Count + ' DELETED=' + $deleted.Count + ' SKIPPED=' + $skipped.Count)
foreach ($s in $skipped) { Write-Host ('  skip  ' + $s) }
if (-not $Apply) { Write-Host 'DRY-RUN only: nothing changed.' }

exit 0
