namespace VisionMaster.Scada
{
    /// <summary>
    /// 运行态的<b>权限出口</b>：此刻是谁在操作、他能不能操作某个受保护的对象。
    ///
    /// 它解决的是什么问题
    /// ---------
    /// "这个按钮只有工程师能按"这条规则，<b>必须在动作执行的那一个出口上判</b>——
    /// 界面上把按钮画灰、把面板藏起来，挡住的只是鼠标，挡不住任何一条直接调接口的路径
    /// （脚本、外部接口、将来接的无人值守任务）。这条口径是 S8 定 <c>ScadaRuntime</c> 时
    /// 就逐字写死的（见 <see cref="ScadaRuntime.RaiseElementEvent"/> 的注释），S12 只是把它兑现。
    ///
    /// 为什么接口定在领域层、实现放在 WPF 侧
    /// ---------
    /// 与 <see cref="IScadaValueSource"/>、<see cref="IScadaNavigator"/> 完全同构：
    /// <b>接口描述的是"要什么"（一个能回答"现在是谁、够不够格"的东西），
    /// 实现解决的是"上哪儿拿"（密码框、状态栏、超时计时器——全是界面能力）</b>。
    /// 领域层知道"未登录按操作员算""高角色含低角色"这两条规则，
    /// 却不知道密码存在哪个文件、登录窗口长什么样；WPF 侧知道这些，
    /// 但一旦让它自己写"未登录算几档"，这条规则的副本就多了一份。
    ///
    /// 实现方的契约
    /// ---------
    /// ① <b>不许抛异常</b>。调用点在鼠标事件处理链上，一次抛异常的表现是"操作员点按钮程序崩了"。
    /// ② <b>无会话时安静返回"操作员"</b>：设计态预览、断言里没挂会话，都会读到本接口。
    /// ③ <b>只读</b>：登录/登出<b>不在本接口上</b>。本接口是"问一句"，改状态是界面的事——
    ///    把它们混在一起，领域层就得认识"密码框"和"超时计时器"。
    /// </summary>
    public interface IScadaAccessPolicy
    {
        /// <summary>
        /// 此刻生效的角色。<b>未登录时返回 <see cref="ScadaRole.Operator"/></b>，不是
        /// <see cref="ScadaRole.Undefined"/>。
        ///
        /// 为什么未登录 = 操作员，而不是"零权限"
        /// ---------
        /// 现场大量存在"开机自动运行、无人值守"的画面：没有人在场，也就没人登录。
        /// 如果未登录 = 零权限，那些画面上的加载钩子（初始化变量、切到首页）会全部被挡，
        /// 软件等于开不起来。工业 HMI 几十年的事实口径是：
        /// <b>操作员是"任何在场的人都有的那部分权限"，密码保护的是高权限操作（改参数、改配方）</b>。
        /// 所以未登录 = 操作员，而"登录成谁"单独由 <see cref="IsLoggedIn"/> 与
        /// <see cref="CurrentUserName"/> 表达。
        /// </summary>
        ScadaRole CurrentRole { get; }

        /// <summary>
        /// 是不是<b>有人登录着</b>。只影响显示（状态栏写"张三（工程师）"还是"未登录（操作员）"）
        /// 与审计署名，<b>不参与权限判定</b>——判定只看 <see cref="CurrentRole"/>。
        ///
        /// 分开表达的理由：把"未登录"和"操作员"合成一个值，就再也说不清
        /// "现在到底是没人登录，还是张三以操作员身份登录着"——而审计要的正是这个区别。
        /// </summary>
        bool IsLoggedIn { get; }

        /// <summary>
        /// 此刻操作者的显示名（审计文件、状态栏用）。未登录时回落成"未登录"，
        /// <b>不返回 null/空串</b>：审计文件里一个空白的用户名列，等于这条记录白记了。
        /// </summary>
        string CurrentUserName { get; }

        /// <summary>
        /// "此刻是谁、他是哪一档"的一句话，形如 <c>admin（管理员）</c> / <c>未登录（操作员）</c>。
        ///
        /// 为什么在接口上给一个<b>拼好的字符串</b>，而不是让每个界面自己拼
        /// ---------
        /// 主窗口状态栏与组态运行窗口底条都要显示这一句。让两处各自拼
        /// （"用户名" + "（" + 角色中文名 + "）"）就有两份实现，而它们会分头演化——
        /// 加一档角色、改一次括号样式，总有一处忘了跟，现场就出现"同一个身份，
        /// 主界面写「工程师」、运行窗口写「Engineer」"这种对不上的读数。
        ///
        /// 未登录时也把"（操作员）"写出来，是为了让操作员明白<b>不是软件坏了，是权限就这么多</b>。
        /// </summary>
        string LoginStateText { get; }

        /// <summary>
        /// 此刻的角色够不够操作一个"要求 <paramref name="required"/>"的对象。
        ///
        /// 三种输入、三种答案：
        /// - <paramref name="required"/> 为 <c>null</c>：<b>不需要权限</b>，一律放行。
        ///   这是绝大多数图元的常态（<c>RequiredRole</c> 没配过就是 null），
        ///   也是"旧 .vms 文件不用迁移"的实现基础。
        /// - <paramref name="required"/> 是非法数值（<see cref="ScadaRole.Undefined"/> 或更高版本存的、
        ///   本版本不认识的值）：<b>一律拒绝</b>。理由——放行等于把"文件里一个不认识的数字"
        ///   解释成"谁都能按"，那是静默的权限放大；拒绝至少是安全的，而且原因会写进日志，
        ///   用户能立刻发现"有个图元的权限配得不对"。
        /// - 正常角色：当前角色达到或高于要求即放行（<b>高角色含低角色</b>，
        ///   管理员不必为了按一个工程师按钮先降级）。
        /// </summary>
        /// <param name="required">对象上声明的要求角色；null = 不限制</param>
        /// <param name="reason">
        /// 拒绝时的一句话原因（"需要「工程师」权限，当前是「操作员」"），
        /// 由调用方原样写进运行日志与审计文件，与属性面板上的提示口径一致。放行时为 null。
        /// </param>
        /// <returns>是否放行</returns>
        bool CanOperate(ScadaRole? required, out string? reason);
    }
}
