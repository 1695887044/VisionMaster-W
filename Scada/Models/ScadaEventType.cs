namespace VisionMaster.Scada
{
    /// <summary>
    /// 组态事件钩子的种类（"画面加载""按钮按下""值改变"这类）。
    ///
    /// 为什么这个枚举住在领域层而不是控件层：它是要写进 .vms 的长期标识之一
    /// （将来"哪个事件配了什么动作"落盘，落的就是这个值），而落盘格式必须比界面稳定——
    /// 属性面板换模板、控件换实现，都不该动摇文件里的取值。本层不依赖 WPF，
    /// 放这里正好让控件层和主程序都往上看，依赖方向不变。
    ///
    /// 数值一旦发布不许改（与 <c>Hmi.</c>TypeKey 同一条规矩），新增只能往后追加。
    /// 名字刻意不带 Page / Button 前缀：Loaded 就是"这个对象装载完了"，
    /// 画面用它是画面加载完，图元用它是图元建完，语义同一个，不必各造一套词。
    ///
    /// S5 起 <see cref="Loaded"/>（画面级，宿主在首帧画完后上报）、<see cref="Pressed"/> 与
    /// <see cref="Released"/>（图元级，画布代发）三条真能触发；S8 起 <see cref="Unloaded"/>
    /// （画面级，运行态停止 / 切走这一页时上报）也接上了；S6 起 <see cref="ValueChanged"/> 等
    /// 四条<b>变量级</b>事件由 <see cref="ScadaVariableEventEngine"/> 边沿判定后触发；
    /// <see cref="InputCompleted"/>（图元级）由可输入图元在自己的"提交成功"分支上报。
    /// 还没接触发源的事件<b>不许出现在任何图元/画面的事件清单里</b>——清单里有一条发不出来的事件，
    /// 用户配上的就是个永远不响的钩子（声明口径见 <c>BuiltInElements</c> 与 <c>ScadaPageEvents</c> 类注释）。
    /// </summary>
    public enum ScadaEventType
    {
        /// <summary>画面加载完成（运行态把该画面显示出来、首帧画完之后触发一次）</summary>
        Loaded = 0,

        /// <summary>卸载（画面被切走或运行停止）；画面级，S8 起真触发</summary>
        Unloaded = 1,

        /// <summary>按下（鼠标按下／触屏按下）；图元级</summary>
        Pressed = 2,

        /// <summary>释放（在同一个图元上抬起）；图元级</summary>
        Released = 3,

        /// <summary>
        /// 更改数值（<b>变量级</b>）：被监视变量的值由一变到另一个值。
        ///
        /// 为什么归"变量级"而不是"图元级"：手册 7.5.2 的"可组态对象"列写明"更改数值 → 变量"。
        /// 语义上它也确实与图元无关——变量是同一个值被十个图元绑着，
        /// 挂到某一个图元上会变成"绑了它的那个图元才能配这个事件"，同一件事有十份配置。
        /// 数值 4 在 S6 就已占位，此处只把它从"图元级"改归"变量级"，取值不变。
        /// </summary>
        ValueChanged = 4,

        /// <summary>值为真（变量级）：BOOL 型变量由假变真（边沿，一直为真不会反复触发）</summary>
        ValueBecameTrue = 5,

        /// <summary>值为假（变量级）：BOOL 型变量由真变假（边沿）</summary>
        ValueBecameFalse = 6,

        /// <summary>
        /// 上限（变量级）：非 BOOL 型变量的值<b>越过了配置的上限</b>（边沿，从"不超"到"超"的那一刻）。
        /// 阈值存在变量事件记录上（见 <see cref="ScadaVariableEvent.UpperLimit"/>），
        /// 而不是变量定义上——手册原话是"超出变量的上限时发生"，但阈值是 SCADA 侧的组态数据，
        /// 不该写进 VM.Core 的变量定义里。
        /// </summary>
        ValueOverUpperLimit = 7,

        /// <summary>下限（变量级）：非 BOOL 型变量的值越过了配置的下限（边沿，从"不低于"到"低于"）</summary>
        ValueUnderLowerLimit = 8,

        /// <summary>
        /// 输入完成时（<b>图元级</b>）：可输入图元把操作员敲的内容<b>成功</b>提交给变量之后触发。
        ///
        /// 为什么归"图元级"而不是"变量级"：手册 7.5.2 的"可组态对象"列写明它挂在
        /// 数字IO域 / 字符IO域 / 日期时间域上——它描述的是"这个框子的这次输入完成了"，
        /// 同一时刻另一个绑着同一个变量的框子并没有被人敲过，两者不是一回事。
        ///
        /// 为什么必须钉在"提交成功"这一刻：输入失败（不是数值、越限、没有写通道、写入被拒）
        /// 时图元留在编辑态、把原因摆在框边，操作员改一下就能重提——那种情况下"输入完成"
        /// 压根没发生，发了就等于告诉用户"你刚才那次算数了"，是比不发更糟的谎报。
        ///
        /// 为什么它不是"值改变"的别名：值改变看的是变量（别人写、通信刷新都算），
        /// 本事件看的是<b>人</b>（只有就地输入成功才发）。两者可以同时发生，也可以各来各的。
        /// </summary>
        InputCompleted = 9,
    }
}
