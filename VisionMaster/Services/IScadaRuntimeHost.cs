using VisionMaster.Scada;

namespace VisionMaster.Services
{
    /// <summary>
    /// 组态<b>运行态宿主</b>：把"把当前这份方案跑起来"这件事收在一个入口上。
    ///
    /// 为什么要有这一层，而不是让编辑器视图模型直接 <c>new ScadaRuntimeWindow().Show()</c>
    /// ---------
    /// 编辑器管的是"怎么改这份文档"，它既不该知道运行窗口长什么样（全屏还是内嵌、
    /// 有没有标题条），也不该负责"同时只能有一个运行窗口""切方案要停掉上一次运行"
    /// "加载耗时记到哪本日志"这些琐事。这些是<b>运行环境的策略</b>，集中在一处才好改，
    /// 也才可能被报表、多屏、无人值守这些别的入口复用。
    ///
    /// 于是分工变成三段，每段只认一件事：
    /// - <see cref="ScadaRuntime"/>（领域层，零 WPF）：此刻该显示哪一页、Loaded 该不该发；
    /// - 本接口（应用层）：单实例、生命周期、日志、用户提示；
    /// - <c>ScadaRuntimeWindow</c>（视图层）：把那一页画出来，仅此而已。
    ///
    /// 编辑器只依赖本接口，因此运行窗口的样式怎么改、甚至换成"嵌进主界面的一块区域"，
    /// 都不必动编辑器一行代码。
    /// </summary>
    public interface IScadaRuntimeHost
    {
        /// <summary>当前是否有一份运行会话活着（供入口决定"运行"按钮要不要置灰/改文案）</summary>
        bool IsRunning { get; }

        /// <summary>
        /// 运行指定文档：按其中的"启动画面"弹出运行窗口。
        ///
        /// 已经在跑时不会开第二个窗口，只把现有窗口带到前台（组态运行态重复启动
        /// 在工控现场是事故源：两份会话会各自写一遍变量）。
        /// 方案里没有可运行的画面时不开窗口，改为提示用户——静默无反应最难查。
        /// </summary>
        void Start(ScadaDocument document);

        /// <summary>结束运行（窗口没开就是空操作）。关方案、切方案、关主界面都会走到这里</summary>
        void Stop();
    }
}
